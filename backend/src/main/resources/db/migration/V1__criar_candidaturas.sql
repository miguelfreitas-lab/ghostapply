BEGIN;

CREATE TABLE candidaturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa VARCHAR(200) NOT NULL CHECK (length(trim(empresa)) > 0),
    titulo VARCHAR(200) NOT NULL CHECK (length(trim(titulo)) > 0),
    url_vaga VARCHAR(2048),
    modalidade VARCHAR(20) NOT NULL CHECK (modalidade IN ('REMOTO', 'HIBRIDO', 'PRESENCIAL')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('SALVA', 'INSCRITO', 'ENTREVISTA', 'OFERTA', 'REJEITADO')),
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
